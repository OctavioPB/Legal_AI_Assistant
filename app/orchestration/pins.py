"""Pinned local models (ADR-014): `config/models.local.yaml`, generated from the Ollama runtime.

    uv run python -m app.orchestration.pins          # (re)generate the file from the runtime
    uv run python -m app.orchestration.pins --check  # compare the file with what is installed

A pin records the exact model digest, the context window and the date it was read from the runtime
that will serve it. If the installed digest differs from the pin, that is a model change and the
golden suite must run before the pin is renewed (CLAUDE.md invariant 2).
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from app.orchestration.aliases import AliasName, AliasRegistry, AliasSpec, default_aliases
from app.orchestration.ollama import model_digest, pin_from_runtime
from app.settings import Settings, get_settings

PINS_PATH = Path(__file__).resolve().parents[2] / "config" / "models.local.yaml"

GEMMA = "gemma4:26b-a4b-it-qat"
QWEN = "qwen3:4b-instruct-2507-q4_K_M"
# alias -> (local model, max answer tokens, fallbacks). Which model backs which alias is a golden
# decision; this is the initial assignment approved with ADR-014 (quality for drafting, speed for
# short utility tasks).
PLAN: dict[AliasName, tuple[str, int, tuple[AliasName, ...]]] = {
    "drafting-primary": (GEMMA, 4096, ("fallback-general",)),
    "drafting-heavy": (GEMMA, 6000, ("drafting-primary",)),
    "adversarial-primary": (GEMMA, 4096, ("drafting-primary",)),
    "cheap-utility": (QWEN, 512, ()),
    "fallback-general": (QWEN, 4096, ()),
}


def generate(path: Path = PINS_PATH, *, base_url: str) -> dict[AliasName, AliasSpec]:
    specs = {
        alias: pin_from_runtime(
            alias, model, max_answer_tokens=tokens, fallbacks=fb, base_url=base_url
        )
        for alias, (model, tokens, fb) in PLAN.items()
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    body = {"aliases": {a: s.model_dump(mode="json") for a, s in specs.items()}}
    header = "# Generated by `python -m app.orchestration.pins` from the local Ollama runtime.\n"
    path.write_text(header + yaml.safe_dump(body, sort_keys=False), encoding="utf-8", newline="\n")
    return specs


def load_registry(path: Path = PINS_PATH) -> AliasRegistry:
    """The pinned registry, or the unpinned default when no pin file exists (aliases then refuse
    to serve calls, loudly)."""
    if not path.exists():
        return AliasRegistry()
    data = yaml.safe_load(path.read_text(encoding="utf-8"))["aliases"]
    specs = default_aliases()
    for alias, spec in data.items():
        specs[alias] = AliasSpec.model_validate(spec)
    return AliasRegistry(specs)


def validate_runtime(registry: AliasRegistry, settings: Settings) -> list[str]:
    """Problems that would only show up at the first long query: the per-call context must hold
    the retrieved context, the system prompt overhead and the answer."""
    prompt_overhead = 1_500  # core + workflow + persona + session layers, with margin
    problems: list[str] = []
    for alias in PLAN:
        spec = registry.spec(alias)
        if not spec.pinned:
            problems.append(f"{alias}: not pinned")
            continue
        need = settings.retrieval_context_budget_tokens + prompt_overhead + spec.max_answer_tokens
        if need > settings.llm_num_ctx:
            problems.append(
                f"{alias}: needs {need} tokens of context, llm_num_ctx is {settings.llm_num_ctx}"
            )
        try:
            registry.validate_budget(alias, settings.retrieval_context_budget_tokens)
        except ValueError as exc:
            problems.append(str(exc))
    return problems


def drift(registry: AliasRegistry, *, base_url: str) -> list[str]:
    """Aliases whose installed model no longer has the pinned digest."""
    out: list[str] = []
    for alias in PLAN:
        pinned = registry.spec(alias).model_id
        if pinned is None:
            out.append(f"{alias}: not pinned")
            continue
        name, digest = pinned.split("@", 1)
        try:
            now = model_digest(name, base_url=base_url)[:12]
        except ValueError:
            out.append(f"{alias}: {name} is no longer installed")
            continue
        if now != digest:
            out.append(f"{alias}: {name} digest changed {digest} -> {now} (a model change)")
    return out


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    s = get_settings()
    if "--check" in args:
        problems = [
            *drift(load_registry(), base_url=s.ollama_url),
            *validate_runtime(load_registry(), s),
        ]
        sys.stdout.write("\n".join(problems) + "\n" if problems else "pins match the runtime\n")
        return 1 if problems else 0
    specs = generate(base_url=s.ollama_url)
    for a, spec in specs.items():
        sys.stdout.write(
            f"{a:20} {spec.model_id}  ctx={spec.context_window}  answer<={spec.max_answer_tokens}\n"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
